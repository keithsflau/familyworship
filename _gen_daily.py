def parse_ref(ref):
    """Turn '約翰福音 14:15–17, 26' into OSIS passages for the CCV reader."""
    raw = ref.replace("–", "-").replace("—", "-").replace(" ", "")
    raw = re.sub(r"下$", "", raw)
    passages = []
    last_book = None
    last_chap = None
    for chunk in re.split(r"[；;]", raw):
        if not chunk:
            continue
        book = None
        rest = chunk
        for name, osis in BOOKS:
            if chunk.startswith(name):
                book = osis
                rest = chunk[len(name):]
                break
        if book is None:
            book = last_book
        if not book:
            raise ValueError("no book in " + ref)
        m = re.match(r"^(\d+):(.+)$", rest)
        if m:
            chap = int(m.group(1))
            secs = m.group(2)
        elif last_chap is not None and re.match(r"^\d", rest):
            chap = last_chap
            secs = rest
        else:
            raise ValueError("bad chunk %r in %s" % (chunk, ref))
        passages.append({
            "osis": book,
            "fhl": OSIS_FHL[book],
            "chap": chap,
            "secs": secs,
        })
        last_book = book
        last_chap = chap
    return passages


def expand_secs(secs):
    nums = []
    for part in secs.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            nums.extend(range(int(a), int(b) + 1))
        else:
            nums.append(int(part))
    return nums


class NCVClient:
    """Fetch only the requested verses from 信望愛《新譯本》JSON API."""

    def __init__(self, cache_path):
        self.cache_path = Path(cache_path)
        self.cache = {}
        if self.cache_path.exists():
            self.cache = json.loads(self.cache_path.read_text(encoding="utf-8"))

    def fetch(self, fhl, chap, secs):
        key = "%s.%s.%s" % (fhl, chap, secs)
        wanted = expand_secs(secs)
        cached = self.cache.get(key)
        if cached and len(cached) == len(wanted):
            return cached
        url = (
            "https://bible.fhl.net/json/qb.php?version=ncv&gb=0&chineses=%s&chap=%s&sec=%s"
            % (quote(fhl), chap, quote(secs))
        )
        verses = self._records(url)
        have = {v["n"] for v in verses}
        for n in wanted:
            if n in have:
                continue
            one = self._records(
                "https://bible.fhl.net/json/qb.php?version=ncv&gb=0&chineses=%s&chap=%s&sec=%s"
                % (quote(fhl), chap, n)
            )
            verses.extend(one)
            time.sleep(0.05)
        verses = [v for v in verses if v["n"] in set(wanted)]
        verses.sort(key=lambda v: v["n"])
        self.cache[key] = verses
        self.cache_path.write_text(json.dumps(self.cache, ensure_ascii=False), encoding="utf-8")
        time.sleep(0.05)
        return verses

    def _records(self, url):
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 FamilyWorship"})
        data = json.loads(urllib.request.urlopen(req, timeout=30).read().decode("utf-8"))
        verses = []
        for rec in data.get("record") or []:
            text = rec.get("bible_text") or ""
            text = re.sub(r"<[^>]+>", "", text)
            text = re.sub(r"\s+", " ", text).strip()
            if text:
                verses.append({"n": int(rec["sec"]), "text": text})
        return verses

    def fill(self, days):
        for d in days:
            for p in d["passages"]:
                p["verses"] = self.fetch(p["fhl"], p["chap"], p["secs"])
                p["src"] = "ncv"


def weekday_sun0(d):
    return (d.weekday() + 1) % 7  # Sun=0 ... Sat=6


def build_days():
    start = date(2026, 9, 17)
    days = []
    sat0 = date(2026, 9, 19)
    for i in range(365):
        d = start + timedelta(days=i)
        iso = d.isoformat()
        wd = weekday_sun0(d)
        if d <= date(2027, 9, 11):
            # which worship Saturday ends this week?
            days_to_sat = (5 - d.weekday()) % 7
            sat = d + timedelta(days=days_to_sat)
            week_i = (sat - sat0).days // 7
            if 0 <= week_i < 52:
                title, main, verse, slots = WEEKS[week_i]
                ref, t, tip = slots[wd]
                sat_flag = wd == 6
                days.append({
                    "date": iso,
                    "dow": ["日", "一", "二", "三", "四", "五", "六"][wd],
                    "week": week_i + 1,
                    "theme": title,
                    "verse": verse,
                    "ref": ref,
                    "title": t,
                    "tip": tip,
                    "sat": sat_flag,
                    "passages": parse_ref(ref),
                })
                continue
        # wrap-up after week 52
        wrap_i = (d - date(2027, 9, 12)).days
        if 0 <= wrap_i < len(WRAP):
            ref, t, tip = WRAP[wrap_i]
            days.append({
                "date": iso,
                "dow": ["日", "一", "二", "三", "四", "五", "六"][wd],
                "week": 52,
                "theme": "一年回顧",
                "verse": "書 24:15 下",
                "ref": ref,
                "title": t,
                "tip": tip,
                "sat": False,
                "passages": parse_ref(ref),
            })
    return days


